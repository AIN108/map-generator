test("SVG 판: 변환·호·둥근 사각형·글자를 적는다", () => {
  const s = new SvgContext(200, 100);
  const c = asCanvas(s);
  c.setTransform(2, 0, 0, 2, 10, 0);
  c.beginPath();
  c.arc(10, 10, 5, 0, Math.PI * 2);
  c.fillStyle = "#ff0000";
  c.fill();
  c.lineWidth = 1.5;
  c.setLineDash([2, 1]);
  c.beginPath();
  c.moveTo(0, 0);
  c.lineTo(20, 0);
  c.stroke();
  c.setLineDash([]);
  c.font = "700 12px \"Noto Sans KR\", sans-serif";
  c.textAlign = "center";
  c.textBaseline = "middle";
  c.fillText("가<나>", 5, 5);
  const out = s.toString();
  assert.match(out, /^<\?xml/);
  assert.match(out, /<path d="M40 20A10 10 0 0 1 20 20A10 10 0 0 1 40 20" fill="#ff0000"\/>/, "원은 호 두 개, 좌표는 변환해서");
  assert.match(out, /stroke-width="3" stroke-dasharray="4 2"/);
  assert.match(out, /<text x="20" y="10"[^>]*font-size="24"[^>]*text-anchor="middle"[^>]*dominant-baseline="central"[^>]*>가&lt;나&gt;<\/text>/);
  assert.doesNotMatch(out, /NaN|undefined/);
});

test("배치도·조감도 그리기 명령을 SVG로 받아 적는다", () => {
  const seed = "svg";
  const site = generateSite(seed, 16);
  const layout = cloneLayout(generateLayout(site, { seed, buildings: 16, hospital: true, name: "" }));
  addNote(layout, 0, 30, "모임 장소");
  const cam = fitCamera(site.boundary, "mid", 1600, 1200);
  const scene = deriveScene(site, layout, seed, "forest", cam);
  const plan = new SvgContext(SITEPLAN_DEFAULTS.width, SITEPLAN_DEFAULTS.height);
  drawSitePlan(asCanvas(plan), scene, SITEPLAN_DEFAULTS);
  const p = plan.toString();
  assert.ok((p.match(/<path /g) ?? []).length > 200);
  assert.ok(p.includes(">모임 장소") || p.includes("모임 장소"), "메모 목록");
  assert.ok(p.includes(layout.buildings[0].name));
  assert.match(p, /<clipPath id="c\d+">/);
  assert.doesNotMatch(p, /NaN|undefined|Infinity/);
  const dl = buildDrawList(scene, cam, makePalette("autumn", "night"), seed, computeForest(scene, cam, seed));
  const bird = new SvgContext(1600, 1200);
  paintCmds(asCanvas(bird), dl);
  const b = bird.toString();
  assert.ok(b.length > 100000);
  assert.match(b, /<linearGradient|<radialGradient/);
  assert.doesNotMatch(b, /NaN|undefined|Infinity/);
});
